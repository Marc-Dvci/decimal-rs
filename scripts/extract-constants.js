#!/usr/bin/env node
// Extracts LN10 and PI from the upstream decimal.js source into a Rust module.
//
// These are 1025-digit string constants. Retyping them, or regenerating them
// from an arbitrary-precision library, would both be ways to introduce a
// single wrong digit a thousand places in — a defect that would surface only
// as a last-digit disagreement in `ln` at a precision nobody tests by hand.
// Extracting them mechanically from the file being ported removes the
// possibility.
//
//     node scripts/extract-constants.js ../upstream-decimal/decimal.js \
//       > crates/decimal-core/src/constants.rs

'use strict';

const fs = require('fs');
const path = process.argv[2] || '../upstream-decimal/decimal.js';
const source = fs.readFileSync(path, 'utf8');

function extract(name) {
  const match = new RegExp(name + " = '([0-9.]+)'").exec(source);
  if (!match) {
    console.error(`extract-constants: could not find ${name} in ${path}`);
    process.exit(1);
  }
  return match[1];
}

// A `concat!` of 72-character chunks, so the constant stays readable in a
// diff and no line runs off the edge of a review window.
function chunks(text) {
  const out = [];
  for (let i = 0; i < text.length; i += 72) {
    out.push('    ' + JSON.stringify(text.slice(i, i + 72)));
  }
  return out.join(',\n');
}

const ln10 = extract('LN10');
const pi = extract('PI');

process.stdout.write(`//! The two transcendental constants the library carries.
//!
//! Both hold 1025 significant digits, which is the ceiling on the precision at
//! which \`ln\`, \`log\` and the trigonometric functions can operate: asking for
//! more raises \`[DecimalError] Precision limit exceeded\`, exactly as the
//! original does.
//!
//! Generated by \`scripts/extract-constants.js\` directly from the upstream
//! source, because a single wrong digit a thousand places in would surface
//! only as a last-digit disagreement at a precision nobody checks by hand.
//! Do not edit by hand; re-run the script.

/// The natural logarithm of 10, to 1025 significant digits.
pub const LN10: &str = concat!(
${chunks(ln10)}
);

/// Pi, to 1025 significant digits.
pub const PI: &str = concat!(
${chunks(pi)}
);

/// The number of significant digits [\`LN10\`] carries.
pub const LN10_PRECISION: i64 = ${ln10.length - 1};

/// The number of significant digits [\`PI\`] carries.
pub const PI_PRECISION: i64 = ${pi.length - 1};

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_constants_have_the_advertised_precision() {
        assert_eq!(LN10.len() as i64 - 1, LN10_PRECISION);
        assert_eq!(PI.len() as i64 - 1, PI_PRECISION);
        assert_eq!(LN10_PRECISION, 1025);
        assert_eq!(PI_PRECISION, 1025);
    }

    #[test]
    fn the_constants_begin_correctly() {
        assert!(LN10.starts_with("2.302585092994045684"));
        assert!(PI.starts_with("3.141592653589793238462643383279"));
    }

    #[test]
    fn the_constants_are_bare_decimal_literals() {
        for constant in [LN10, PI] {
            assert_eq!(constant.matches('.').count(), 1);
            assert!(constant
                .chars()
                .all(|c| c.is_ascii_digit() || c == '.'));
        }
    }
}
`);
