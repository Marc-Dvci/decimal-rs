#!/usr/bin/env node
// Generates the oracle fixture for `decimal_core::format::number_to_string`.
//
// The ECMAScript `Number::toString` algorithm is the single largest source of
// silent divergence in a JavaScript-to-Rust port of this library: the digits
// agree with Rust's, but the notation thresholds do not, and a mistake shows
// up not as one obviously-wrong conversion but as a hundred unrelated-looking
// failures in modules that merely happen to construct a Decimal from a number.
//
// So rather than trusting a reading of the specification, this dumps what Node
// actually prints, for a corpus that deliberately crowds the boundaries where
// the notation changes. The Rust test reads the file back and compares.
//
// Values are keyed by their IEEE-754 bit pattern rather than by their decimal
// text, so the fixture cannot itself be distorted by a formatting question.
//
//     node scripts/dump-number-fixture.js > crates/decimal-core/tests/fixtures/number-to-string.txt

'use strict';

const values = [];
const seen = new Set();

function add(v) {
  if (typeof v !== 'number' || Number.isNaN(v)) return;
  const buf = Buffer.alloc(8);
  buf.writeDoubleBE(v);
  const bits = buf.toString('hex');
  if (seen.has(bits)) return;
  seen.add(bits);
  values.push([bits, String(v)]);
}

// Small integers, where the fast path in the original's constructor lives.
for (let i = 0; i <= 1000; i++) add(i);

// Every power of ten within range, and its immediate neighbours. The notation
// switches at 1e21 and 1e-7, so these straddle both thresholds.
for (let k = -330; k <= 330; k++) {
  const p = Number('1e' + k);
  add(p);
  add(-p);
  add(p * 1.5);
  add(p * 9.999999999999999);
  add(nextAfter(p, Infinity));
  add(nextAfter(p, -Infinity));
}

// Values with the maximum 17 significant digits, which exercise the
// shortest-round-trip machinery rather than the notation rules.
for (let k = 0; k < 400; k++) {
  add(Math.PI * Math.pow(10, k - 200));
  add(Math.E * Math.pow(10, k - 200));
  add(Math.sqrt(2) * Math.pow(10, k - 200));
}

// The extremes: denormals, the largest finite double, and the boundaries of
// exact integer representation.
add(Number.MIN_VALUE);
add(Number.MAX_VALUE);
add(Number.EPSILON);
add(Number.MAX_SAFE_INTEGER);
add(Number.MIN_SAFE_INTEGER);
add(Number.MAX_SAFE_INTEGER + 2);
add(0);
add(-0);
add(Infinity);
add(-Infinity);
add(5e-324);
add(2.2250738585072014e-308); // smallest normal
add(2.225073858507201e-308); // largest denormal

// A pseudo-random spread, with a fixed seed so the fixture is reproducible.
let seed = 20260731;
function random() {
  seed = (seed * 1103515245 + 12345) & 0x7fffffff;
  return seed / 0x7fffffff;
}
for (let i = 0; i < 4000; i++) {
  const exponent = Math.floor(random() * 620) - 310;
  add(random() * Math.pow(10, exponent));
}

function nextAfter(x, direction) {
  if (Number.isNaN(x) || x === direction) return x;
  if (x === 0) return direction > 0 ? Number.MIN_VALUE : -Number.MIN_VALUE;
  const buf = Buffer.alloc(8);
  buf.writeDoubleLE(x);
  let bits = buf.readBigUInt64LE();
  bits += (x > 0) === (direction > x) ? 1n : -1n;
  buf.writeBigUInt64LE(bits & 0xffffffffffffffffn);
  return buf.readDoubleLE();
}

process.stdout.write(
  '# ECMAScript Number::toString, as produced by Node ' + process.version + '.\n' +
  '# Generated by scripts/dump-number-fixture.js. Each line is the IEEE-754\n' +
  '# big-endian bit pattern of a double, a space, and String(value).\n' +
  '# ' + values.length + ' values.\n'
);
for (const [bits, text] of values) {
  process.stdout.write(bits + ' ' + text + '\n');
}
